"""Regenerate docs/RESULTS.md: measured numbers on the SYNTHETIC sample corpus.

    python scripts/make_results.py          # writes docs/RESULTS.md
    python scripts/make_results.py --check  # exit 1 if the committed file is stale

A test runs the --check logic, so the published numbers always match the code and data.
"""

from __future__ import annotations

import shutil
import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

from sigharness.corpus import FieldMapping, load_corpus  # noqa: E402
from sigharness.gate import compare, read_baseline, snapshot  # noqa: E402
from sigharness.rules import load_rules  # noqa: E402
from sigharness.scoring import run  # noqa: E402

EX = ROOT / "examples"
OUT = ROOT / "docs" / "RESULTS.md"


def pct(x: float | None) -> str:
    return "n/a" if x is None else f"{x * 100:.1f}%"


def render() -> str:
    mapping = FieldMapping.load(EX / "fieldmap.yml")
    fixtures = load_corpus([EX / "corpus"])
    rules = load_rules([EX / "rules"])
    res = run(rules, fixtures, mapping)
    families: dict[str, list[int]] = {}
    for fx in fixtures:
        key = "/".join(fx.logsource[k] for k in ("product", "category", "service") if k in fx.logsource)
        pos_neg = families.setdefault(key, [0, 0])
        pos_neg[0 if fx.expect else 1] += 1

    lines = [
        "# Measured results (synthetic data)",
        "",
        "> **All numbers on this page come from a synthetic, hand-written corpus.** They show that",
        "> the harness computes and gates correctly on known inputs. They are **not** a measure of",
        "> how well these sample rules detect attacks in a real environment.",
        "",
        "Generated by `python scripts/make_results.py`; `tests/test_results.py` fails if this file",
        "no longer matches the code and data.",
        "",
        "## Dataset",
        f"- {len(fixtures)} labeled events in `examples/corpus/`, generated by",
        "  `scripts/make_sample_corpus.py`. Written by hand to resemble Sysmon-style process",
        "  creation, ECS-style proxy logs and the Okta System Log. Not captured from any real",
        "  system; hostnames use reserved example domains (RFC 2606), public IPs come from the RFC 5737",
        "  documentation ranges.",
        "- Each rule has attack events (labeled `expect`) and benign look-alikes (unlabeled: must",
        "  stay quiet), including one evasion fixture (`lnx-0204`) and three events that the",
        "  sample rules deliberately get wrong, recorded as known debt in `examples/baseline.json`.",
        "",
        "| Log source | Attack events | Benign events |",
        "|---|--:|--:|",
    ]
    for key, (p, n) in sorted(families.items()):
        lines.append(f"| {key} | {p} | {n} |")
    lines += [
        "",
        "## Methodology",
        f"- `sigharness run` with {len(rules)} rules from `examples/rules/` and `examples/fieldmap.yml`.",
        "- A rule is scored on every event whose logsource it applies to: TP (labeled, fired),",
        "  FN (labeled, quiet), FP (unlabeled, fired), TN (unlabeled, quiet).",
        "- Tuning PRs: each directory in `examples/tuning/` is overlaid on the sample rules and",
        "  gated with `compare` (vs base rules) and `check` (vs the committed baseline).",
        "",
        "## Per-rule scores",
        "",
        "| Rule | TP | FP | FN | TN | Precision | Recall |",
        "|---|--:|--:|--:|--:|--:|--:|",
    ]
    for s in sorted(res.scores, key=lambda s: s.title.lower()):
        lines.append(f"| {s.title} | {s.tp} | {s.fp} | {s.fn} | {s.tn} | "
                     f"{pct(s.precision)} | {pct(s.recall)} |")
    t = res.totals
    lines += ["", f"Totals: TP {t['TP']}, FP {t['FP']}, FN {t['FN']}, TN {t['TN']}.", ""]

    lines += ["### Known debt in the baseline", ""]
    for s in sorted(res.scores, key=lambda s: s.title.lower()):
        for fx, o in sorted(s.outcomes.items()):
            if o in ("FP", "FN"):
                note = next(f.note for f in fixtures if f.id == fx)
                lines.append(f"- {o} `{fx}` on *{s.title}*: {note}")
    lines += ["", "## Tuning PR gate outcomes", "",
              "| PR | compare | check | Regressions | Improvements |", "|---|---|---|---|---|"]
    base_snap = snapshot(res)
    baseline = read_baseline(EX / "baseline.json")
    with tempfile.TemporaryDirectory() as tmp:
        for pr in sorted(p for p in (EX / "tuning").iterdir() if p.is_dir()):
            head = Path(tmp) / pr.name
            shutil.copytree(EX / "rules", head)
            shutil.copytree(pr, head, dirs_exist_ok=True)
            hres = run(load_rules([head]), fixtures, mapping)
            r1, r2 = compare(base_snap, hres), compare(baseline, hres)

            def fmt(cs):
                return ", ".join(f"`{c.fixture}` {c.before}→{c.after}" for c in cs) or "none"

            lines.append(f"| {pr.name} | {'FAIL' if r1.failed else 'PASS'} | "
                         f"{'FAIL' if r2.failed else 'PASS'} | {fmt(r1.of('regression'))} | "
                         f"{fmt(r1.of('improvement'))} |")
    lines += [
        "",
        "## Limitations",
        "- Synthetic and small: 100% on a rule means it matches the events written for it, which",
        "  were written by the same project as the rule. Real telemetry is noisier and more varied.",
        "- The evaluator runs rules in memory; a SIEM running the pySigma-converted query can",
        "  differ (see `docs/PYSIGMA_DIFFERENCES.md`).",
        "- Benign look-alikes were chosen to exercise each rule's filters and edges, not sampled",
        "  from real traffic, so FP rates here say nothing about production alert volume.",
        "",
    ]
    return "\n".join(lines)


def main(argv: list[str]) -> int:
    text = render()
    if "--check" in argv:
        current = OUT.read_text(encoding="utf-8") if OUT.exists() else ""
        if current != text:
            print("docs/RESULTS.md is stale: run python scripts/make_results.py", file=sys.stderr)
            return 1
        return 0
    OUT.write_text(text, encoding="utf-8")
    print(f"wrote {OUT}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
